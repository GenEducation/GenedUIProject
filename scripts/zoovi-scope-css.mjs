// Scopes the Zoovi website prototype styles (render_handoff_v72/prototypes/home) to the marketing pages.
//
//   node scripts/zoovi-scope-css.mjs <prototypes/home>
//
// The prototypes style the whole document (:root tokens, html/body, bare class names like .nav or .story).
// Inside the app every selector is prefixed with .zv-site (the marketing pages' wrapper), and the styles that
// were inline in one page with .zv-site[data-page=…], so pages never style each other or the portals.
// html-level state classes (.rm reduced motion, .speech-mode) stay on <html>: `.rm .x` becomes
// `html.rm .zv-site .x`. Asset URLs are rewritten to /zoovi/. Re-run after the prototypes change.
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const SRC = path.resolve(process.argv[2] ?? "../render_handoff_v72/prototypes/home");
const OUT = path.resolve(import.meta.dirname, "../src/features/marketing/styles");

const FONTS = `/* The prototypes' two rounded faces, self-hosted (copies of src/fonts). Declared under their plain family
   names because the device screen (engine/screens.js) draws text on a canvas with "600 30px Fredoka". */
@font-face { font-family: "Fredoka"; src: url("/zoovi/fonts/Fredoka-Variable.woff2") format("woff2"); font-weight: 300 700; font-display: swap; }
@font-face { font-family: "Nunito"; src: url("/zoovi/fonts/Nunito-Variable.woff2") format("woff2"); font-weight: 200 1000; font-display: swap; }
/* The prototypes were designed on browser defaults; the app's Tailwind preflight (a cascade layer) resets
   headings, lists, images, buttons… Unlayered and zero-specificity, this puts the defaults back inside the
   marketing pages only, and every prototype rule below still wins. Replaced elements only get back the box
   properties preflight changes: \`all: revert\` there would also drop their width/height/fill attributes. */
.zv-site :where(h1, h2, h3, h4, h5, h6, p, ol, ul, li, dl, dd, figure, blockquote, hr,
  button, input, textarea, select, summary, details, a, b, strong, small, mark, table, th, td) { all: revert; }
.zv-site :where(img, svg, video, canvas) { display: revert; vertical-align: revert; max-width: revert; }
`;

const HTML_STATE = /^((?:html)?(?:\.(?:rm|speech-mode))+)(?=$|[\s>+~:])/;

function scopeSelector(sel, scope) {
  const s = sel.trim();
  if (s === ":root" || s === "html" || s === "body") return scope;
  const m = s.match(HTML_STATE);
  if (m) {
    const state = m[1].startsWith("html") ? m[1] : `html${m[1]}`;
    const rest = s.slice(m[1].length).trim();
    return rest ? `${state} ${scope} ${rest}` : `${state} ${scope}`;
  }
  const root = s.match(/^(html|body|:root)([.:[][^\s]*)?(\s.*)?$/);
  if (root) return `${scope}${root[2] ?? ""}${root[3] ?? ""}`;
  return `${scope} ${s}`;
}

// tokens.css has three orphaned declaration lines (a deleted rule's body) after .nav-page:focus-visible.
// Browsers skip them as part of a broken selector; drop them so the file parses.
const ORPHAN = /\n {2}width: 28px; height: 28px; border-radius: 50%; display: grid; place-items: center; text-decoration: none;\n {2}font: 600 13px\/1 var\(--display\); transition: transform \.35s var\(--spring\), box-shadow \.25s;\n\}/;

function scope(css, scopeSel, from) {
  const root = postcss.parse(css.replace(ORPHAN, ""), { from });
  root.walkAtRules("import", (r) => r.remove()); // Google Fonts: replaced by FONTS
  root.walkRules((rule) => {
    const parent = rule.parent;
    if (parent?.type === "atrule" && /keyframes$/.test(parent.name)) return;
    rule.selectors = rule.selectors.map((sel) => scopeSelector(sel, scopeSel));
  });
  root.walkDecls((d) => {
    // body { overflow-x: hidden } moves onto the wrapper, where `hidden` would make it a scroll container and
    // break every position: sticky stage inside it; `clip` cuts the overflow without that.
    if (d.prop === "overflow-x" && d.value === "hidden" && d.parent?.selector === scopeSel) d.value = "clip";
    d.value = d.value.replace(/url\((["']?)(?:\.\.\/)?assets\//g, "url($1/zoovi/");
  });
  return root.toString();
}

const inlineStyle = (file) => {
  const html = fs.readFileSync(path.join(SRC, file), "utf8");
  return [...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");
};

const HEAD = (from) => `/* Generated by scripts/zoovi-scope-css.mjs from prototypes/home/${from}. Do not edit by hand. */\n`;
// Each sheet applies only to the pages whose prototype linked it (parents.html: tokens, parents, portal;
// educators.html: tokens, parents, educators; index.html: tokens). :where() keeps the page test free of
// specificity, so the prototypes' own cascade (link order, then the page's inline <style>) still decides.
// SiteShell imports the files in that same order.
const only = (...pages) => `.zv-site:where(${pages.map((p) => `[data-page="${p}"]`).join(", ")})`;
const read = (f) => fs.readFileSync(path.join(SRC, f), "utf8");
const jobs = [
  ["tokens.css", read("shared/tokens.css"), ".zv-site", "shared/tokens.css", FONTS],
  ["parents.css", read("shared/parents.css"), only("parents", "educators"), "shared/parents.css"],
  ["portal.css", read("shared/portal.css"), only("parents"), "shared/portal.css"],
  ["educators.css", read("shared/educators.css"), only("educators"), "shared/educators.css"],
  ["page-home.css", inlineStyle("index.html"), only("home"), "index.html <style>"],
  ["page-parents.css", inlineStyle("parents.html"), only("parents"), "parents.html <style>"],
  ["page-educators.css", inlineStyle("educators.html"), only("educators"), "educators.html <style>"],
];
fs.mkdirSync(OUT, { recursive: true });
for (const [name, css, sel, from, pre = ""] of jobs) {
  fs.writeFileSync(path.join(OUT, name), HEAD(from) + pre + scope(css, sel, from));
  console.log("wrote", path.relative(process.cwd(), path.join(OUT, name)));
}
