/**
 * Which backend each admin API call goes to.
 *
 * The admin console is moving from the MVP backend to the new one a screen
 * group at a time. This module is the only thing that knows both origins and
 * the only thing that decides between them, so the two admin services cannot
 * drift apart on where a call should land.
 *
 * **The default is the MVP, always.** A path with no rule, an unset new-backend
 * URL, a group that is not switched on, a method that is not a known read — all
 * of them return the MVP origin. That safety property comes from the rule table
 * being an allow-list rather than from an `else` branch someone can edit later:
 * to send traffic somewhere new you must add a row, and adding a row is visible
 * in review.
 *
 * Configuration (build-time; Next inlines `NEXT_PUBLIC_*`, so changing these on
 * a running deployment does nothing until it is rebuilt):
 *
 * - `NEXT_PUBLIC_API_URL`                        the MVP gateway. Everything else falls back here.
 * - `NEXT_PUBLIC_ADMIN_API_URL`                  the new gateway. Empty ⇒ nothing moves.
 * - `NEXT_PUBLIC_ADMIN_BACKEND_GROUPS`           comma list; whose GETs go to the new backend.
 * - `NEXT_PUBLIC_ADMIN_BACKEND_WRITE_GROUPS`     comma list; whose writes do. Narrowed to the read list.
 * - `NEXT_PUBLIC_ADMIN_AUTH_URL`                 where the admin signs in. Empty ⇒ the MVP, as before.
 */

export type AdminGroup = "accounts" | "schools" | "analytics" | "ingestions";

export type AdminMethod = "GET" | "HEAD" | "POST" | "PUT" | "PATCH" | "DELETE";

const KNOWN_GROUPS: readonly AdminGroup[] = [
  "accounts",
  "schools",
  "analytics",
  "ingestions",
];

/** Methods that only read. Everything else is treated as a write. */
const READ_METHODS: ReadonlySet<string> = new Set(["GET", "HEAD"]);

interface Rule {
  /** Matched against the path with the query string removed. */
  readonly prefix: string;
  readonly group: AdminGroup;
  /**
   * Route by the WRITE list whatever the method. For a flow whose GET and POST
   * must agree — see the bulk-import rule below.
   */
  readonly alwaysWrite?: boolean;
}

/**
 * Ordered, most specific first; first match wins.
 *
 * Only paths listed here can ever leave the MVP. `/admin/devices*`,
 * `/admin/agents*`, `/admin/wakeword-models*`, `/admin/lab/*` and
 * `/lab/devices/:id/logs` are deliberately absent — those screens are under
 * maintenance and their routes stay where they are.
 */
export const ADMIN_ROUTE_RULES: readonly Rule[] = [
  { prefix: "/admin/analytics", group: "analytics" },

  // Listed ahead of /admin/users so the intent is visible in the table rather
  // than implied by prefix length. `alwaysWrite` keeps the template download
  // and the upload that consumes it on ONE backend: split across two, the
  // console would hand out a template generated by a different service than
  // the one about to parse it.
  { prefix: "/admin/users/import", group: "accounts", alwaysWrite: true },
  { prefix: "/admin/users", group: "accounts" },
  { prefix: "/admin/stats", group: "accounts" },
  { prefix: "/admin/students", group: "accounts" },
  { prefix: "/admin/parents", group: "accounts" },

  // /admin/parents and /admin/partners are two characters apart and live in
  // DIFFERENT groups. Matching is segment-aware for exactly this reason.
  { prefix: "/admin/partners", group: "schools" },
  { prefix: "/admin/teacher-students", group: "schools" },
  { prefix: "/admin/teachers", group: "schools" },
  { prefix: "/admin/enrollments", group: "schools" },

  { prefix: "/admin/ingestions", group: "ingestions" },
];

function trimBase(value: string | undefined): string {
  // Neither admin service stripped a trailing slash before this module
  // existed. With a single origin a stray slash produced "//admin/..." against
  // both backends and gateways tolerated it; with two origins it breaks
  // exactly one of them, and the symptom reads as "the new backend is broken".
  return (value ?? "").trim().replace(/\/+$/, "");
}

function parseGroups(value: string | undefined): ReadonlySet<AdminGroup> {
  const wanted = (value ?? "")
    .split(",")
    .map((token) => token.trim().toLowerCase())
    .filter(Boolean);

  const known = wanted.filter((token): token is AdminGroup =>
    (KNOWN_GROUPS as readonly string[]).includes(token),
  );

  if (process.env.NODE_ENV !== "production") {
    const unknown = wanted.filter((token) => !(known as string[]).includes(token));
    if (unknown.length) {
      console.warn(
        `[adminApiRouting] ignoring unknown group(s): ${unknown.join(", ")}. ` +
          `Known groups: ${KNOWN_GROUPS.join(", ")}.`,
      );
    }
  }

  return new Set(known);
}

const MVP_BASE = trimBase(process.env.NEXT_PUBLIC_API_URL);
const NEW_BASE = trimBase(process.env.NEXT_PUBLIC_ADMIN_API_URL);

/**
 * Where the admin console signs in.
 *
 * Separate from `NEXT_PUBLIC_API_URL`, which every other screen's sign-in uses,
 * because the console is moving backend one screen group at a time and its
 * login was the last thing still tied to the MVP — the one dependency that
 * would keep the MVP running even with every admin screen moved over.
 *
 * Both stacks issue the same token: HS256, the same claims, the same
 * `JWT_SECRET_KEY`. So this chooses the issuer and nothing else, and unsetting
 * it puts the console back on the MVP's login with no other change — the same
 * rollback the group flags give the screens.
 *
 * It must be the new backend's **gateway**, not its api. The gateway strips
 * `/auth` before forwarding, so `/auth/sign-in` reaches the api as `/sign-in`;
 * point this at the api directly and every sign-in is a 404 that reads as
 * "the new backend has no login".
 */
const ADMIN_AUTH_BASE = trimBase(process.env.NEXT_PUBLIC_ADMIN_AUTH_URL);

const READ_GROUPS = parseGroups(process.env.NEXT_PUBLIC_ADMIN_BACKEND_GROUPS);

// Intersected with the read list, not asserted against it. A config that names
// a write group without the matching read group is a mistake, and the safe
// reading of a mistake is "stay on the MVP" — not a throw at module load,
// which would blank the whole console, since every admin view imports this.
const WRITE_GROUPS: ReadonlySet<AdminGroup> = new Set(
  [...parseGroups(process.env.NEXT_PUBLIC_ADMIN_BACKEND_WRITE_GROUPS)].filter((g) =>
    READ_GROUPS.has(g),
  ),
);

if (process.env.NODE_ENV !== "production") {
  const dropped = [...parseGroups(process.env.NEXT_PUBLIC_ADMIN_BACKEND_WRITE_GROUPS)].filter(
    (g) => !READ_GROUPS.has(g),
  );
  if (dropped.length) {
    console.warn(
      `[adminApiRouting] write group(s) without a matching read group, so their ` +
        `writes stay on the MVP: ${dropped.join(", ")}.`,
    );
  }
}

/**
 * What this bundle decided at load, for tests and for showing an operator why
 * their flag "did nothing" — the usual answer being that `NEXT_PUBLIC_*` is
 * baked in at build time and the deployment has not been rebuilt.
 */
export const ADMIN_ROUTING = Object.freeze({
  mvpBase: MVP_BASE,
  newBase: NEW_BASE,
  authBase: ADMIN_AUTH_BASE || MVP_BASE,
  readGroups: READ_GROUPS,
  writeGroups: WRITE_GROUPS,
});

function stripQuery(pathWithQuery: string): string {
  const cut = pathWithQuery.indexOf("?");
  return cut === -1 ? pathWithQuery : pathWithQuery.slice(0, cut);
}

function matches(path: string, prefix: string): boolean {
  // Segment-aware: "/admin/devices/DEV-1" is under "/admin/devices", but
  // "/admin/devices-archive" is a different screen and must not match.
  return path === prefix || path.startsWith(`${prefix}/`);
}

function ruleFor(pathWithQuery: string): Rule | null {
  const path = stripQuery(pathWithQuery);
  return ADMIN_ROUTE_RULES.find((rule) => matches(path, rule.prefix)) ?? null;
}

/** Where `/auth/sign-in` goes for the admin console. The MVP until one is configured. */
export function adminAuthBase(): string {
  return ADMIN_AUTH_BASE || MVP_BASE;
}

/**
 * Where the console reads shared *reference* data that is not an `/admin/*` path.
 *
 * Today that is one endpoint: `/rag/taxonomy/subjects`, the subject catalogue the
 * Create-account modal and the Teachers filter need. It is not in the rule table
 * because the table keys on `/admin/...` paths, so before this it fell through to
 * `API_BASE_URL` and stayed on the MVP however many groups had moved — the console
 * kept one live MVP call on every admin page load. With the MVP stopped the
 * catalogue came back empty, and an empty catalogue renders as *no subject chips at
 * all*, so an admin could not give a new TEACHER a subject. Phase 7 found this; no
 * parity script could, because they compare one backend's response with the other's
 * rather than watching which host the console asks.
 *
 * Both stacks serve it byte-identically (verified against the mini on 2026-10-22,
 * CBSE 7 subjects and ICSE 1, identical), and the new gateway already routes
 * `/rag/taxonomy` to core. So this follows the migration as a whole rather than one
 * group: the moment any group is on the new backend, reference reads go there too.
 * Nothing configured ⇒ the MVP, the same rollback as every other flag here.
 */
export function adminReferenceBase(): string {
  return NEW_BASE && READ_GROUPS.size > 0 ? NEW_BASE : MVP_BASE;
}

/**
 * Whether reads of `group` go to the new backend.
 *
 * For the one case where the two backends do not serve the same shape: the
 * Ingestions screen. The MVP lists rows of its `partner_ingestions` table; the
 * new backend lists the chapter sources it actually ingests, which have no
 * chunk count and do have a run state. So the group switches which *view*
 * renders, not only which host it calls — and the rollback stays one flag:
 * group off ⇒ old view ⇒ MVP, exactly as before.
 *
 * Prefer `adminUrl` everywhere else. A view asking this question is a view
 * whose two backends disagree about the data, which should stay rare.
 */
export function readsNewBackend(group: AdminGroup): boolean {
  return Boolean(NEW_BASE) && READ_GROUPS.has(group);
}

/** The group a path belongs to, or null when nothing claims it (⇒ MVP). */
export function adminGroupForPath(pathWithQuery: string): AdminGroup | null {
  return ruleFor(pathWithQuery)?.group ?? null;
}

/** The origin this call must go to. Never throws. */
export function adminApiBase(pathWithQuery: string, method: AdminMethod): string {
  // Belt and braces: with nowhere to route to, no group list can route anything.
  if (!NEW_BASE) return MVP_BASE;

  const rule = ruleFor(pathWithQuery);
  if (!rule) return MVP_BASE;

  // Anything that is not a known read consults the WRITE list, so a method
  // added later fails towards the MVP rather than towards the new backend.
  const enabled =
    rule.alwaysWrite || !READ_METHODS.has(method) ? WRITE_GROUPS : READ_GROUPS;

  return enabled.has(rule.group) ? NEW_BASE : MVP_BASE;
}

/**
 * The absolute URL for an admin call. The only function service code needs.
 *
 * `method` is required on purpose: were it optional and defaulting to GET, a
 * write that forgot to pass it would be judged against the read list — which is
 * a superset of the write list — and could be sent to the new backend. Making
 * it required turns that into a compile error instead.
 */
export function adminUrl(pathWithQuery: string, method: AdminMethod): string {
  return `${adminApiBase(pathWithQuery, method)}${pathWithQuery}`;
}
